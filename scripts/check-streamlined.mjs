// UI workflow checks with deterministic IPC fixtures; real backend coverage is in selftest.ts.
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const server = await createServer({ server: { port: 1433, strictPort: true }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1094, height: 688 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(String(error)));
  await page.goto('http://127.0.0.1:1433/preview.html');
  await page.waitForSelector('.ai-input textarea:not(:disabled)');
  await page.evaluate(async () => {
    const { api } = await import('/src/lib/ipc.ts');
    window.calls = { scans: [], agent: 0, clear: 0 };
    const originalAsk = api.aiAsk;
    api.aiAsk = (...args) => { window.calls.agent++; return originalAsk(...args); };
    let generated = false;
    const tactic = { id: 7, gameId: 42, ply: 9, fen: 'rn1qkbnr/ppp2p1p/3p2p1/4N3/2B1P1b1/2N5/PPPP1PPP/R1BQK2R b KQkq - 0 5', moves: ['g4d1', 'c4f7', 'e8e7', 'c3d5'], solver: 'white', kind: 'mate', themes: ['mateIn2'], owner: 'opponent', white: 'Other player', black: 'Me', date: null, attempts: 0 };
    api.tacticsForGame = async () => generated ? [tactic] : [];
    api.tacticNext = async () => generated ? tactic : null;
    api.tacticsScan = async (_job, settings, onProgress) => {
      window.calls.scans.push(settings); generated = true;
      const progress = { gameIndex: 0, games: 1, gameId: 42, label: '', stage: 'search', done: 1, total: 1, found: 1, finished: true };
      onProgress(progress); return progress;
    };
    api.tacticCheck = async (_id, index, uci) => ({ result: tactic.moves[index] === uci ? 'correct' : 'incorrect', solved: index === 3, reply: index === 1 ? 'e8e7' : null });
    api.tacticAttempt = async () => tactic;
    api.clearHistory = async () => { window.calls.clear++; return 4; };
    const s = window.__outpost.getState();
    s.loadPgn('[White "Other player"]\n[Black "Me"]\n\n1. e4 e5 2. Nf3 d6 3. Bc4 Bg4 4. Nc3 g6 5. Nxe5 Bxd1 6. Bxf7+ Ke7 7. Nd5# 1-0', { gameId: 42, game: { id: 42, white: 'Other player', black: 'Me', account: 'Me' } });
    s.next();
  });
  assert.equal(await page.locator('.position-overview, .position-tabs, .agent-provider').count(), 0);
  assert.equal(await page.evaluate(() => window.calls.agent), 0);
  const original = await page.evaluate(() => { const s = window.__outpost.getState(); return s.tree.nodes[s.current].fen; });
  await page.getByRole('button', { name: 'Generate puzzles', exact: true }).click();
  await page.getByRole('button', { name: 'Back to game', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.__outpost.getState().view), 'analyze');
  assert.equal(await page.locator('.engine-panel').count(), 0);
  await page.waitForFunction(() => document.querySelector('.puzzle-status')?.textContent.includes('White to play'));
  const move = async (from, to) => {
    await page.locator(`.board [data-square="${from}"]`).click();
    await page.locator(`.board [data-square="${to}"]`).click();
  };
  await move('c4', 'f7');
  await page.waitForFunction(() => document.querySelector('.puzzle-status')?.textContent.includes('White to play'));
  await move('c3', 'd5');
  await page.getByText('Solved!', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Back to game', exact: true }).click();
  assert.equal(await page.evaluate(() => { const s = window.__outpost.getState(); return s.tree.nodes[s.current].fen; }), original);
  assert.equal(await page.evaluate(() => window.__outpost.getState().orientation), 'black');
  assert.equal(await page.evaluate(() => window.calls.agent), 0);
  await page.getByLabel('Ask the AI assistant').fill('What is the plan?');
  await page.getByLabel('Send', { exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.ai-msg.assistant').length && !document.querySelector('.ai-input textarea').disabled);
  assert.equal(await page.evaluate(() => window.calls.agent), 1);
  await page.evaluate(async () => {
    const { useGameChat } = await import('/src/views/gameChat.ts');
    const session = window.__outpost.getState().analysisSession;
    for (let i = 0; i < 20; i++) useGameChat.getState().append(session, { role: 'assistant', content: `Earlier message ${i}: ${'A full explanation of the position. '.repeat(6)}` });
  });
  await page.waitForTimeout(100);
  assert(await page.locator('.ai-thread').evaluate((el) => el.scrollHeight > el.clientHeight));
  await page.locator('.ai-thread').evaluate((el) => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll', { bubbles: true })); });
  await page.evaluate(async () => { const { useGameChat } = await import('/src/views/gameChat.ts'); useGameChat.getState().append(window.__outpost.getState().analysisSession, { role: 'assistant', content: 'New message while reading older messages.' }); });
  assert.equal(await page.locator('.ai-thread').evaluate((el) => el.scrollTop), 0);
  await page.getByLabel('Configure agent in Settings').click();
  await page.getByLabel('Use Codex (ChatGPT)').waitFor();
  assert.equal(await page.locator('.sidebar').getByRole('button', { name: 'Agent', exact: true }).count(), 0);
  await page.evaluate(() => window.__outpost.getState().setView('tactics'));
  await page.getByText('White to play and mate', { exact: true }).waitFor();
  await move('e1', 'e8');
  await page.getByText('Solved!', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Generate puzzles from my games', exact: true }).click();
  const scans = await page.evaluate(() => window.calls.scans);
  assert.deepEqual(scans[0].gameIds, [42]);
  assert.equal(scans[0].rescan, false);
  assert.equal(scans[1].rescan, false);
  assert.equal(scans[1].maxGames, 10000);
  assert.equal(scans[1].gameIds, undefined);
  await page.evaluate(() => window.__outpost.getState().setView('games'));
  await page.getByRole('button', { name: 'Clear history', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.evaluate(() => window.calls.clear), 0);
  await page.getByRole('button', { name: 'Clear history', exact: true }).click();
  await page.getByRole('button', { name: 'Clear game history', exact: true }).click();
  await page.waitForFunction(() => window.calls.clear === 1);
  await page.evaluate(() => window.__outpost.getState().openImport('lichess'));
  assert.equal(await page.getByRole('tab', { name: /Screenshot/ }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: plain chat, manual prompts only, scrollback, Settings, inline puzzle solving/restoration, basic puzzles, batch options, clear confirmation, no screenshot import');
} finally { await browser.close(); await server.close(); }
